import { mkdir, readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';
const source = new URL('../web/contracts/openapi.json', import.meta.url);
const target = new URL('../web/src/generated/api-types.ts', import.meta.url);
const shared = new URL('../packages/contracts/src/api-types.ts', import.meta.url);
const reexport = '// Generated by scripts/contracts.mjs; the REST contract is shared by web and mobile.\nexport type * from "@futeio/contracts";\n';
const generated = astToString(await openapiTS(JSON.parse(await readFile(source, 'utf8')), { defaultNonNullable: false }));
if (process.argv.includes('--write')) {
  await mkdir(new URL('../packages/contracts/src/', import.meta.url), { recursive: true });
  await writeFile(shared, generated);
  await writeFile(target, reexport);
} else if ((await readFile(shared, 'utf8')) !== generated || (await readFile(target, 'utf8')) !== reexport) throw new Error('Run pnpm contracts:generate and commit updated types.');
else console.log('Shared web/mobile REST contracts are current.');
