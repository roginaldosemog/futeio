import * as ImagePicker from 'expo-image-picker';
import { ImageManipulator, SaveFormat } from 'expo-image-manipulator';
import { File } from 'expo-file-system';

export async function selectProfilePhoto(): Promise<string | null> {
  // The system photo picker grants access to the selected image. No camera,
  // microphone or broad photo-library access is requested by this flow.
  const selection = await ImagePicker.launchImageLibraryAsync({
    mediaTypes: ['images'], allowsMultipleSelection: false, allowsEditing: false,
    exif: false, base64: false, quality: 1,
  });
  if (selection.canceled || !selection.assets?.length) return null;
  const asset = selection.assets[0]!;
  if (!/^(file|content):\/\//.test(asset.uri) || !asset.width || !asset.height) throw new Error('Não foi possível abrir esta foto.');
  const context = ImageManipulator.manipulate(asset.uri, { maxWidth: 512, maxHeight: 512 });
  try {
    if (Math.max(asset.width, asset.height) > 512) {
      context.resize(asset.width >= asset.height ? { width: 512, height: null } : { width: null, height: 512 });
    }
    const image = await context.renderAsync();
    try {
      const result = await image.saveAsync({ format: SaveFormat.JPEG, compress: 0.8, base64: true });
      try {
        if (!result.base64 || result.base64.length > 2_796_204) throw new Error('Escolha uma foto menor para o perfil.');
        return result.base64;
      } finally {
        // Delete only the new file generated by the manipulator, never the
        // original photo selected from the device library.
        new File(result.uri).delete();
      }
    } finally { image.release(); }
  } finally { context.release(); }
}
